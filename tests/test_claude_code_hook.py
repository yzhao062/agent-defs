@pytest.fixture
def config(tmp_path, monkeypatch):
    # Protocol assertions are independent of host process-launch latency.
    # Deadline handling is exercised separately with zero and exhausted budgets.
    monkeypatch.setattr(hook, "SCAN_BUDGET_S", 2)
    config = hook.default_config()
    config["log_path"] = str(tmp_path / "log.jsonl")
    # This file exercises the protocol over the starter set, and ``measured``
    # below builds its evidence from that set. A subprocess that also loaded the
    # shipped bundle would be running rules the evidence never covered, which is
    # its own behaviour and has its own test.
    config["bundle"] = ""
    return config


def measured(config, rules=STARTER_RULES, n=2995):
    # Unit fixture only. Production evidence is generated by calibrate on files.
    m = asdict(BenignFiring(n, 0, u95_zero_hits(n), "unit fixture, not field evidence", "2026-09-04"))
    config["evidence"] = {"fingerprint": hook.fingerprint(rules, config["surfaces"]),
                          "bundle": m.copy(), "rules": {r.id: m.copy() for r in rules}}
    return config


def payload(value, event="PostToolUse"):
    return {"hook_event_name": event, "tool_name": "Read",
            "tool_input": value if event == "PreToolUse" else {"file_path": "data.txt"},
            "tool_response": value}


def attack():
    return STARTER_RULES[0].examples_positive[0]


def call_cli(tmp_path, args, text="{}"):
    env = dict(os.environ, PYTHONPATH=str(Path(__file__).resolve().parents[1] / "src"))
    return subprocess.run([sys.executable, "-m", "agent_defs.hooks.claude_code", *args], input=text,
                          env=env, cwd=tmp_path, capture_output=True, text=True, timeout=5)



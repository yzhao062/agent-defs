def test_real_guard_settings_merge_without_touching_installed_files(tmp_path):
    reference = Path.home() / ".claude" / "settings.json"
    guard_path = Path.home() / ".claude" / "hooks" / "guard.py"
    if not reference.exists() or not guard_path.exists():
        pytest.skip("installed guard is only available on the reference machine")
    before, guard_before = reference.read_bytes(), guard_path.read_bytes()
    original = json.loads(before.decode("utf-8-sig"))
    assert "guard.py" in json.dumps(original["hooks"])
    settings, config_path = tmp_path / "settings.json", tmp_path / "config.json"
    settings.write_bytes(before)
    hook.install(settings, config_path, confirm=True)
    once = settings.read_bytes()
    hook.install(settings, config_path, confirm=True)
    assert settings.read_bytes() == once
    hook.install(settings, config_path, uninstall=True, confirm=True)
    assert json.loads(settings.read_text()) == original
    assert reference.read_bytes() == before and guard_path.read_bytes() == guard_before



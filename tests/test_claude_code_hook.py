@pytest.mark.parametrize("bad", ["missing", "stale", "ten", "hits", "bundle_hits", "nan", "negative", "no_corpus"])
def test_bad_evidence_never_promotes(config, bad):
    measured(config)
    config["sources"]["builtin"] = "DENY"
    evidence = config["evidence"]
    if bad == "missing":
        evidence.pop("bundle")
    elif bad == "stale":
        evidence["fingerprint"] = "wrong"
    elif bad == "ten":
        measured(config, n=10)
    elif bad == "bundle_hits":
        evidence["bundle"]["hits"] = 1
    else:
        for m in evidence["rules"].values():
            if bad == "hits":
                m["hits"] = 1
            elif bad == "nan":
                m["u95"] = float("nan")
            elif bad == "negative":
                m["trials"] = -1
            elif bad == "no_corpus":
                m["corpus"] = ""
    assert hook.process(payload(attack()), config) == {}


